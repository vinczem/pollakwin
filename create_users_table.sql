-- PostgreSQL schema. Schedule and feedback columns follow the existing PHP queries.
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    won BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_won ON users (won);

CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS users_updated_at ON users;
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS feedback (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nev VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE REFERENCES users(email),
    holhallott INTEGER NOT NULL,
    mennyielegedett INTEGER NOT NULL,
    szakirany INTEGER NOT NULL,
    szoveg TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS orak (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kezdete TIME NOT NULL,
    vege TIME NOT NULL
);

CREATE TABLE IF NOT EXISTS oktatok (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nev VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS korok (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ora INTEGER NOT NULL REFERENCES orak(id),
    oktato INTEGER NOT NULL REFERENCES oktatok(id),
    tantargy VARCHAR(255),
    tanterem VARCHAR(255),
    csoport VARCHAR(255),
    holvan VARCHAR(255),
    szin VARCHAR(255) NOT NULL,
    rendezveny INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_korok_event_color ON korok (rendezveny, szin);
